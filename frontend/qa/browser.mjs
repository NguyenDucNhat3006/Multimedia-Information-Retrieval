/** QA trình duyệt local: video thật cho seek; ground truth mock chỉ trong fixture được gắn nhãn. */
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const reportDir = path.join(projectRoot, 'docs', 'reports');
mkdirSync(reportDir, { recursive: true });
const executablePath = process.env.CS336_BROWSER_PATH ?? [
  'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',
  'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe',
].find(existsSync);
if (!executablePath) throw new Error('Cần browser có sẵn; đặt CS336_BROWSER_PATH. Không tự tải browser.');
const baseUrl = process.env.CS336_BASE_URL ?? 'http://127.0.0.1:8000';
const fixtureUrl = process.env.CS336_FIXTURE_URL ?? 'http://127.0.0.1:8001';
const skipReal = process.env.CS336_SKIP_REAL === 'true';
const reportFilename = skipReal ? 'ui-fixture-browser-report.json' : 'ui-browser-report.json';
const browser = await chromium.launch({ executablePath, headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, locale: 'vi-VN' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const checks = [];
const stamp = Date.now();
const time = ms => `${String(Math.floor(ms / 3600000)).padStart(2, '0')}:${String(Math.floor((ms % 3600000) / 60000)).padStart(2, '0')}:${String(Math.floor((ms % 60000) / 1000)).padStart(2, '0')}.${String(ms % 1000).padStart(3, '0')}`;
const waitPost = (pageRef, route) => pageRef.waitForResponse(response => new URL(response.url()).pathname === route && response.request().method() === 'POST', { timeout: 120000 });

try {
  if (!skipReal) {
  await page.goto(baseUrl, { waitUntil: 'networkidle' });
  await page.getByText('Backend kết nối', { exact: true }).waitFor();
  assert.equal(await page.locator('html').getAttribute('lang'), 'vi');
  const caps = await (await context.request.get(`${baseUrl}/api/capabilities`)).json();
  assert.equal(caps.fixture, false, 'Real UI QA must target real dataset');
  await page.screenshot({ path: path.join(reportDir, 'ui-real-empty.png'), fullPage: true });
  await page.getByLabel('Nội dung truy vấn', { exact: true }).fill('Người dẫn chương trình trong trường quay truyền hình');
  await page.locator('#visual-query').fill('A presenter speaking in a television studio');
  const searchPromise = waitPost(page, '/api/search');
  await page.getByRole('button', { name: 'Tìm kiếm', exact: true }).click();
  const searchResponse = await searchPromise;
  assert.equal(searchResponse.status(), 200);
  const search = await searchResponse.json();
  assert.ok(search.results.length > 0);
  await page.locator('.result-card').first().waitFor();
  await page.locator('.result-card img').evaluateAll(images => images.forEach(image => { image.loading = 'eager'; }));
  await page.waitForFunction(() => [...document.querySelectorAll('.result-card img')].every(image => image.complete && image.naturalWidth > 0));
  await page.screenshot({ path: path.join(reportDir, 'ui-real.png'), fullPage: false });
  const chosen = search.results.find(item => item.timestamp_ms > 0) ?? search.results[0];
  await page.getByRole('button', { name: `Xem ${chosen.media_item_name} tại ${time(chosen.timestamp_ms)}`, exact: true }).click();
  await page.locator('.inspector video').waitFor();
  await page.waitForFunction(expected => {
    const video = document.querySelector('.inspector video');
    return video && video.readyState >= 2 && !video.seeking && Math.abs(video.currentTime - expected) < .15;
  }, chosen.timestamp_ms / 1000, { timeout: 30000 });
  const playerTime = await page.locator('.inspector video').evaluate(video => ({ currentTime: video.currentTime, duration: video.duration, readyState: video.readyState }));
  checks.push({ check: 'Real search and player seek', result: 'pass', results: search.results.length, expected_ms: chosen.timestamp_ms, player: playerTime });
  await page.locator('.inspector video').evaluate(async video => { video.muted = true; await video.play(); });
  await page.waitForFunction(expected => document.querySelector('.inspector video').currentTime > expected + .15, chosen.timestamp_ms / 1000);
  await page.locator('.inspector video').evaluate((video, timestamp) => { video.pause(); video.currentTime = timestamp / 1000; }, chosen.timestamp_ms);
  await page.waitForFunction(() => { const video = document.querySelector('.inspector video'); return video && video.readyState >= 2 && !video.seeking; });
  checks.push({ check: 'Real browser decodes and plays media bytes, then returns to anchor', result: 'pass' });
  const feedbackPromise = waitPost(page, '/api/feedback');
  await page.locator('.feedback-actions').getByRole('button', { name: 'Liên quan', exact: true }).click();
  assert.equal((await feedbackPromise).status(), 200);
  await page.locator('.feedback-actions button[aria-pressed="true"]').waitFor();
  checks.push({ check: 'Relevance feedback real API', result: 'pass' });
  const existingCandidates = await (await context.request.get(`${baseUrl}/api/candidates`)).json();
  const previouslySaved = existingCandidates.candidates.some(item => item.keyframe_id === chosen.keyframe_id);
  if (!previouslySaved) {
    const savePromise = waitPost(page, '/api/candidates');
    await page.getByRole('button', { name: 'Lưu vào ứng viên', exact: true }).click();
    assert.equal((await savePromise).status(), 200);
    await page.getByRole('button', { name: 'Đã lưu · bấm để bỏ lưu', exact: true }).waitFor();
  }
  const submission = page.locator('.submission-panel');
  await submission.getByLabel('Loại đáp án', { exact: true }).selectOption('QA');
  await submission.getByLabel('Evaluation', { exact: true }).selectOption('local-mock');
  await submission.getByLabel('Task / round key', { exact: true }).fill(`browser-real-dry-${stamp}`);
  await submission.getByLabel('Đáp án QA (chuỗi số)', { exact: true }).fill('007');
  assert.equal(await submission.getByRole('button', { name: 'Ghi nhận dry run', exact: true }).isDisabled(), true);
  const previewPromise = waitPost(page, '/api/dres/preview');
  await submission.getByRole('button', { name: 'Xem trước JSON', exact: true }).click();
  const previewResponse = await previewPromise;
  assert.equal(previewResponse.status(), 200);
  const preview = await previewResponse.json();
  assert.equal(preview.payload.answerSets[0].answers[0].text, `007-${chosen.media_item_name}-${chosen.timestamp_ms}`);
  await submission.screenshot({ path: path.join(reportDir, 'ui-real-dres.png') });
  await page.evaluate(() => window.scrollTo(0, 600));
  await page.screenshot({ path: path.join(reportDir, 'ui-real-inspector.png'), fullPage: false });
  const dryPromise = waitPost(page, '/api/dres/submit');
  await submission.getByRole('button', { name: 'Ghi nhận dry run', exact: true }).click();
  const dryResponse = await dryPromise;
  assert.equal(dryResponse.status(), 200);
  const dry = await dryResponse.json();
  assert.equal(dry.status, 'dry_run');
  checks.push({ check: 'Real DRES preview and deliberate dry run, QA 007', result: 'pass', status: dry.status });
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByText('Backend kết nối', { exact: true }).waitFor();
  await page.getByRole('button', { name: /^Ứng viên/ }).click();
  await page.getByRole('button', { name: `Xem ${chosen.media_item_name} tại ${time(chosen.timestamp_ms)}`, exact: true }).waitFor();
  checks.push({ check: 'Candidates persist after full reload', result: 'pass' });
  await page.getByRole('button', { name: `Xem ${chosen.media_item_name} tại ${time(chosen.timestamp_ms)}`, exact: true }).click();
  await page.locator('.feedback-actions button[aria-pressed="true"]').waitFor();
  checks.push({ check: 'Feedback session and labels persist after full reload', result: 'pass' });
  await page.getByRole('button', { name: 'Đóng chi tiết', exact: true }).click();
  if (!previouslySaved) { await context.request.delete(`${baseUrl}/api/candidates/${encodeURIComponent(chosen.keyframe_id)}`); }
  await page.getByRole('button', { name: 'Đánh giá', exact: true }).click();
  await page.getByRole('heading', { name: 'Đo chất lượng bằng nhãn thật.', exact: true }).waitFor();
  await page.screenshot({ path: path.join(reportDir, 'ui-evaluation.png'), fullPage: true });
  await page.getByRole('button', { name: 'Dữ liệu & index', exact: true }).click();
  await page.getByRole('heading', { name: 'Video đã đăng ký', exact: true }).waitFor();
  await page.screenshot({ path: path.join(reportDir, 'ui-data.png'), fullPage: true });
  await page.getByRole('button', { name: 'Lịch sử', exact: true }).click();
  await page.getByRole('heading', { name: 'Mỗi truy vấn đều có dấu vết.', exact: true }).waitFor();
  checks.push({ check: 'Data, evaluation and history navigation', result: 'pass' });
  await page.getByRole('button', { name: 'Truy vấn video', exact: true }).click();
  await page.getByRole('tab', { name: 'Ảnh mẫu', exact: true }).click();
  const referenceImage = await context.request.get(`${baseUrl}${chosen.thumbnail_url}`);
  assert.equal(referenceImage.status(), 200);
  await page.locator('#query-image').setInputFiles({ name: 'qa-reference.jpg', mimeType: 'image/jpeg', buffer: await referenceImage.body() });
  await page.getByLabel('Top k', { exact: true }).selectOption('12');
  const imagePromise = waitPost(page, '/api/search/image');
  await page.getByRole('button', { name: 'Tìm bằng ảnh', exact: true }).click();
  const imageResponse = await imagePromise;
  assert.equal(imageResponse.status(), 200);
  const imageResults = await imageResponse.json();
  assert.equal(imageResults.results.length, 12);
  checks.push({ check: 'Real image upload and top-k query parameter honored', result: 'pass', results: imageResults.results.length });
  await page.getByRole('button', { name: /^Kết quả/ }).click();
  await page.locator('.result-card img').first().waitFor();
  await page.locator('.result-card img').evaluateAll(images => images.forEach(image => { image.loading = 'eager'; }));
  await page.waitForFunction(() => [...document.querySelectorAll('.result-card img')].every(image => image.complete && image.naturalWidth > 0));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: path.join(reportDir, 'ui-mobile.png'), fullPage: false });
  const overflow = await page.evaluate(() => ({ width: window.innerWidth, scrollWidth: document.documentElement.scrollWidth }));
  assert.ok(overflow.scrollWidth <= overflow.width + 1, `Mobile overflow: ${JSON.stringify(overflow)}`);
  checks.push({ check: '390px mobile layout without horizontal page overflow', result: 'pass' });
  }

  // Fixture màu có ground truth đã khai báo: đỏ từ 0 đến 1999 ms, không suy từ ranking.
  const fixturePage = await context.newPage();
  fixturePage.on('pageerror', error => errors.push(error.message));
  await fixturePage.goto(fixtureUrl, { waitUntil: 'networkidle' });
  const fixtureCaps = await (await context.request.get(`${fixtureUrl}/api/capabilities`)).json();
  assert.equal(fixtureCaps.fixture, true);
  await fixturePage.getByText(/Đang dùng fixture để kiểm thử tích hợp/).waitFor();
  const fixtureData = await (await context.request.get(`${fixtureUrl}/api/data`)).json();
  const fixtureVideo = fixtureData.videos.find(item => item.source_batch === 'fixture');
  assert.ok(fixtureVideo);
  await fixturePage.getByRole('button', { name: 'Dữ liệu & index', exact: true }).click();
  await fixturePage.locator('.mock-task summary').click();
  const task = fixturePage.locator('.mock-task-body');
  const fixtureTaskKey = `browser-fixture-${stamp}`;
  await task.getByLabel('Task key', { exact: true }).fill(fixtureTaskKey);
  await task.getByLabel('Loại task', { exact: true }).selectOption('qa');
  await task.getByLabel('Video ground truth', { exact: true }).selectOption(fixtureVideo.video_uid);
  await task.getByLabel('Bắt đầu (ms)', { exact: true }).fill('0');
  await task.getByLabel('Kết thúc (ms)', { exact: true }).fill('1999');
  await task.getByLabel('Đáp án QA', { exact: true }).fill('007');
  const mockStartPromise = waitPost(fixturePage, '/api/dres/mock/start');
  await task.getByRole('button', { name: 'Bắt đầu task mock', exact: true }).click();
  assert.equal((await mockStartPromise).status(), 200);
  await fixturePage.getByRole('button', { name: 'Truy vấn video', exact: true }).click();
  await fixturePage.getByRole('tab', { name: 'OCR', exact: true }).click();
  await fixturePage.getByLabel('Nội dung truy vấn', { exact: true }).fill('red');
  const fixtureSearchPromise = waitPost(fixturePage, '/api/search');
  await fixturePage.getByRole('button', { name: 'Tìm kiếm', exact: true }).click();
  const fixtureSearch = await (await fixtureSearchPromise).json();
  const fixtureChosen = fixtureSearch.results.find(item => item.timestamp_ms === 1000) ?? fixtureSearch.results.find(item => item.timestamp_ms < 2000);
  assert.ok(fixtureChosen);
  await fixturePage.getByRole('button', { name: `Xem ${fixtureChosen.media_item_name} tại ${time(fixtureChosen.timestamp_ms)}`, exact: true }).click();
  const fixtureSubmission = fixturePage.locator('.submission-panel');
  await fixtureSubmission.getByLabel('Loại đáp án', { exact: true }).selectOption('QA');
  await fixtureSubmission.getByLabel('Chế độ', { exact: true }).selectOption('mock');
  await fixtureSubmission.getByLabel('Evaluation', { exact: true }).selectOption('local-mock');
  await fixtureSubmission.getByLabel('Task / round key', { exact: true }).fill(fixtureTaskKey);
  await fixtureSubmission.getByLabel('Đáp án QA (chuỗi số)', { exact: true }).fill('007');
  const fixturePreviewPromise = waitPost(fixturePage, '/api/dres/preview');
  await fixtureSubmission.getByRole('button', { name: 'Xem trước JSON', exact: true }).click();
  assert.equal((await fixturePreviewPromise).status(), 200);
  const mockPromise = waitPost(fixturePage, '/api/dres/submit');
  await fixtureSubmission.getByRole('button', { name: 'Nộp vào mock', exact: true }).click();
  const mockResponse = await mockPromise;
  assert.equal(mockResponse.status(), 200);
  const mock = await mockResponse.json();
  assert.equal(mock.status, 'correct');
  await fixturePage.getByText('Đúng theo ground truth mock', { exact: true }).waitFor();
  await fixtureSubmission.screenshot({ path: path.join(reportDir, 'ui-fixture-mock.png') });
  checks.push({ check: 'Fixture only: declared ground truth → OCR → preview → mock QA submit', result: 'pass', status: mock.status });
  assert.deepEqual(errors, []);
  writeFileSync(path.join(reportDir, reportFilename), JSON.stringify({ tested_at: new Date().toISOString(), browser: executablePath, real_base_url: skipReal ? null : baseUrl, fixture_base_url: fixtureUrl, fixture_only_mock_ground_truth: true, checks, javascript_errors: errors, limitation: 'Real local smoke validates workflow, not retrieval relevance or a dataset benchmark. No live DRES request.' }, null, 2));
  console.log(JSON.stringify({ checks: checks.length, result: 'pass', javascript_errors: errors, report: `docs/reports/${reportFilename}` }, null, 2));
} catch (error) {
  await page.screenshot({ path: path.join(reportDir, 'ui-failure.png'), fullPage: true }).catch(() => {});
  writeFileSync(path.join(reportDir, reportFilename), JSON.stringify({ tested_at: new Date().toISOString(), checks, error: error.message, javascript_errors: errors }, null, 2));
  throw error;
} finally { await browser.close(); }
